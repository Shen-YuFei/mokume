export function translate(text, values = {}) {
  let result = state.language === "zh-CN"
    ? CHINESE_TRANSLATIONS[text] || CHINESE_HELP_TRANSLATIONS[text] || text
    : text;
  Object.entries(values).forEach(([name, value]) => {
    result = result.replaceAll(`{${name}}`, String(value));
  });
  return result;
}

export function setTranslatedText(element, text, values = {}) {
  element.dataset.i18n = text;
  element.dataset.i18nValues = JSON.stringify(values);
  element.textContent = translate(text, values);
}

export function setTranslatedAttribute(element, attribute, text, values = {}) {
  element.setAttribute(`data-i18n-${attribute}`, text);
  element.setAttribute(`data-i18n-${attribute}-values`, JSON.stringify(values));
  element.setAttribute(attribute, translate(text, values));
}

export function translatedElement(tag, className, text, values = {}) {
  const element = document.createElement(tag);
  if (className) element.className = className;
  setTranslatedText(element, text, values);
  return element;
}
